import javax.swing.*;
import javax.swing.border.TitledBorder;
import javax.swing.table.DefaultTableModel;
import java.awt.*;
import java.io.IOException;
import java.text.SimpleDateFormat;
import java.util.*;
import java.util.List;
import java.util.regex.Pattern;

/** Sri Lanka Railway express train booking - Swing GUI built entirely in code. */
public class TrainBookingApp extends JFrame {
    private static final int MAX_SEATS = 4;
    private static final Color FREE = new Color(125, 200, 125);
    private static final Color BOOKED = new Color(225, 95, 95);
    private static final Color PICKED = new Color(95, 150, 230);
    private static final Pattern ID_PATTERN = Pattern.compile("\\d{9}[VvXx]|\\d{12}");
    private static final Pattern PHONE_PATTERN = Pattern.compile("0\\d{9}");

    private final DataStore store = new DataStore("data");
    private final SimpleDateFormat fmt = new SimpleDateFormat("yyyy-MM-dd");

    private final JComboBox<String> routeBox = new JComboBox<>();
    private final JComboBox<Train> trainBox = new JComboBox<>();
    private final JSpinner dateSpinner =
            new JSpinner(new SpinnerDateModel(new Date(), null, null, Calendar.DAY_OF_MONTH));
    private final JComboBox<Integer> carriageBox = new JComboBox<>();
    private final JPanel seatGrid = new JPanel();
    private final JTextField idF = new JTextField(14);
    private final JTextField nameF = new JTextField(14);
    private final JTextField contactF = new JTextField(14);
    private final JLabel infoLabel = new JLabel(" ");
    private final JLabel modeLabel = new JLabel("New booking");
    private final DefaultTableModel model =
            new DefaultTableModel(new String[]{"Ref", "ID No", "Name", "Contact", "Seats"}, 0) {
                @Override public boolean isCellEditable(int r, int c) { return false; }
            };
    private final JTable table = new JTable(model);
    private final Set<String> selected = new LinkedHashSet<>();
    private String editingRef = null;
    private boolean loading = false;

    public TrainBookingApp() {
        super("Sri Lanka Railway - Express Train Booking");
        try {
            store.load();
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Could not read data files: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
        setDefaultCloseOperation(EXIT_ON_CLOSE);
        dateSpinner.setEditor(new JSpinner.DateEditor(dateSpinner, "yyyy-MM-dd"));
        buildLayout();

        for (String r : store.routes()) routeBox.addItem(r);
        routeBox.addActionListener(e -> fillTrains());
        trainBox.addActionListener(e -> { if (!loading) refreshAll(); });
        dateSpinner.addChangeListener(e -> refreshAll());
        carriageBox.addActionListener(e -> { if (!loading) buildGrid(); });
        table.getSelectionModel().addListSelectionListener(e -> {
            if (!loading && !e.getValueIsAdjusting()) loadSelectedBooking();
        });
        fillTrains();

        setSize(1000, 700);
        setLocationRelativeTo(null);
    }

    // ---------- layout (all generated by code) ----------
    private void buildLayout() {
        JPanel top = new JPanel(new FlowLayout(FlowLayout.LEFT, 10, 8));
        top.add(new JLabel("Route:"));
        top.add(routeBox);
        top.add(new JLabel("Train:"));
        top.add(trainBox);
        top.add(new JLabel("Travel date:"));
        top.add(dateSpinner);

        JPanel legend = new JPanel(new FlowLayout(FlowLayout.LEFT, 8, 2));
        legend.add(new JLabel("Carriage:"));
        legend.add(carriageBox);
        legend.add(swatch(FREE, "Available"));
        legend.add(swatch(PICKED, "Selected"));
        legend.add(swatch(BOOKED, "Booked"));

        JPanel gridWrap = new JPanel(new FlowLayout(FlowLayout.CENTER, 0, 10));
        gridWrap.add(seatGrid);
        JPanel seatPanel = new JPanel(new BorderLayout());
        seatPanel.setBorder(new TitledBorder("Seat arrangement"));
        seatPanel.add(legend, BorderLayout.NORTH);
        seatPanel.add(new JScrollPane(gridWrap), BorderLayout.CENTER);
        seatPanel.add(infoLabel, BorderLayout.SOUTH);

        JPanel form = new JPanel(new GridBagLayout());
        form.setBorder(new TitledBorder("Customer details"));
        GridBagConstraints g = new GridBagConstraints();
        g.insets = new Insets(5, 5, 5, 5);
        g.fill = GridBagConstraints.HORIZONTAL;
        g.gridx = 0; g.gridy = 0; g.gridwidth = 2;
        modeLabel.setFont(modeLabel.getFont().deriveFont(Font.BOLD));
        form.add(modeLabel, g);
        g.gridwidth = 1;
        addRow(form, g, 1, "ID number:", idF);
        addRow(form, g, 2, "Name:", nameF);
        addRow(form, g, 3, "Contact no:", contactF);

        JButton book = new JButton("Book selected seats");
        JButton update = new JButton("Update (alter) booking");
        JButton cancel = new JButton("Cancel booking");
        JButton clear = new JButton("Clear / new");
        book.addActionListener(e -> doBook());
        update.addActionListener(e -> doUpdate());
        cancel.addActionListener(e -> doCancel());
        clear.addActionListener(e -> refreshAll());
        JPanel buttons = new JPanel(new GridLayout(0, 1, 6, 6));
        buttons.add(book);
        buttons.add(update);
        buttons.add(cancel);
        buttons.add(clear);
        g.gridx = 0; g.gridy = 4; g.gridwidth = 2;
        g.insets = new Insets(15, 5, 5, 5);
        form.add(buttons, g);
        g.gridy = 5; g.weighty = 1; g.fill = GridBagConstraints.BOTH;
        form.add(new JLabel("<html><small>Max " + MAX_SEATS + " seats per customer.<br>"
                + "To alter: pick a booking in the table, change the seats / details, then press Update.<br>"
                + "To cancel: pick a booking in the table, then press Cancel.</small></html>"), g);

        JSplitPane center = new JSplitPane(JSplitPane.HORIZONTAL_SPLIT, seatPanel, form);
        center.setResizeWeight(0.65);

        table.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        table.setAutoCreateRowSorter(true);
        JScrollPane tableScroll = new JScrollPane(table);
        tableScroll.setBorder(new TitledBorder("Bookings for selected train and date"));
        tableScroll.setPreferredSize(new Dimension(900, 190));

        setLayout(new BorderLayout());
        add(top, BorderLayout.NORTH);
        add(center, BorderLayout.CENTER);
        add(tableScroll, BorderLayout.SOUTH);
    }

    private static JPanel swatch(Color c, String text) {
        JPanel p = new JPanel(new FlowLayout(FlowLayout.LEFT, 3, 0));
        JLabel box = new JLabel("   ");
        box.setOpaque(true);
        box.setBackground(c);
        box.setBorder(BorderFactory.createLineBorder(Color.DARK_GRAY));
        p.add(box);
        p.add(new JLabel(text));
        return p;
    }

    private static void addRow(JPanel p, GridBagConstraints g, int row, String label, JComponent c) {
        g.gridx = 0; g.gridy = row; g.weightx = 0;
        p.add(new JLabel(label), g);
        g.gridx = 1; g.weightx = 1;
        p.add(c, g);
    }

    // ---------- data -> view ----------
    private Train current() { return (Train) trainBox.getSelectedItem(); }

    private String date() { return fmt.format((Date) dateSpinner.getValue()); }

    private void fillTrains() {
        loading = true;
        trainBox.removeAllItems();
        String route = (String) routeBox.getSelectedItem();
        if (route != null) for (Train t : store.trainsOnRoute(route)) trainBox.addItem(t);
        loading = false;
        refreshAll();
    }

    private void refreshAll() {
        loading = true;
        selected.clear();
        editingRef = null;
        idF.setText("");
        nameF.setText("");
        contactF.setText("");
        modeLabel.setText("New booking");
        Train t = current();
        carriageBox.removeAllItems();
        if (t != null) for (int i = 1; i <= t.carriages; i++) carriageBox.addItem(i);
        loading = false;
        buildGrid();
        fillTable();
    }

    private void buildGrid() {
        seatGrid.removeAll();
        Train t = current();
        if (t != null && carriageBox.getSelectedItem() != null) {
            int c = (Integer) carriageBox.getSelectedItem();
            Set<String> taken = store.bookedSeats(t.no, date(), editingRef);
            seatGrid.setLayout(new GridLayout(0, 5, 6, 6)); // 2 seats | aisle | 2 seats
            for (int s = 1; s <= t.seatsPerCarriage; s++) {
                if ((s - 1) % 4 == 2) seatGrid.add(new JLabel(""));
                final String key = c + "-" + s;
                JButton b = new JButton(String.valueOf(s));
                b.setOpaque(true);
                b.setFocusPainted(false);
                b.setBorder(BorderFactory.createLineBorder(Color.DARK_GRAY));
                b.setPreferredSize(new Dimension(52, 36));
                if (taken.contains(key)) { b.setBackground(BOOKED); b.setEnabled(false); }
                else if (selected.contains(key)) b.setBackground(PICKED);
                else b.setBackground(FREE);
                b.addActionListener(e -> toggle(key));
                seatGrid.add(b);
            }
        }
        seatGrid.revalidate();
        seatGrid.repaint();
        updateInfo();
    }

    private void updateInfo() {
        Train t = current();
        if (t == null) { infoLabel.setText(" "); return; }
        int booked = store.bookedSeats(t.no, date(), null).size();
        String status = booked >= t.totalSeats() ? "  -  FULLY BOOKED" : "";
        List<String> names = new ArrayList<>();
        for (String k : selected) names.add(pretty(k));
        infoLabel.setText("<html>&nbsp;" + t.name + " (" + t.carriages + " carriages x " + t.seatsPerCarriage
                + " seats): " + booked + " / " + t.totalSeats() + " booked" + status
                + "<br>&nbsp;Selected: " + (names.isEmpty() ? "none" : String.join(", ", names)) + "</html>");
    }

    private static String pretty(String key) {
        String[] p = key.split("-");
        return "C" + p[0] + "-S" + p[1];
    }

    private void fillTable() {
        loading = true;
        model.setRowCount(0);
        Train t = current();
        if (t != null) {
            for (Map.Entry<String, List<Booking>> e : store.bookingsByRef(t.no, date()).entrySet()) {
                Booking f = e.getValue().get(0);
                List<String> seats = new ArrayList<>();
                for (Booking b : e.getValue()) seats.add(pretty(b.seatKey()));
                model.addRow(new Object[]{e.getKey(), f.idNo, f.name, f.contact, String.join(", ", seats)});
            }
        }
        loading = false;
    }

    private void loadSelectedBooking() {
        int row = table.getSelectedRow();
        Train t = current();
        if (row < 0 || t == null) return;
        String ref = (String) model.getValueAt(table.convertRowIndexToModel(row), 0);
        List<Booking> list = store.bookingsByRef(t.no, date()).get(ref);
        if (list == null) return;
        Booking f = list.get(0);
        idF.setText(f.idNo);
        nameF.setText(f.name);
        contactF.setText(f.contact);
        selected.clear();
        for (Booking b : list) selected.add(b.seatKey());
        editingRef = ref;
        modeLabel.setText("Editing booking " + ref);
        buildGrid();
    }

    private void toggle(String key) {
        if (!selected.remove(key)) {
            if (selected.size() >= MAX_SEATS) {
                warn("A customer can book up to " + MAX_SEATS + " seats.");
                return;
            }
            selected.add(key);
        }
        buildGrid();
    }

    // ---------- actions ----------
    private String validate(Train t, String excludeRef) {
        String id = idF.getText().trim(), name = nameF.getText().trim(), phone = contactF.getText().trim();
        if (!ID_PATTERN.matcher(id).matches()) return "Enter a valid NIC (9 digits + V/X, or 12 digits).";
        if (name.isEmpty()) return "Enter the customer's name.";
        if (!PHONE_PATTERN.matcher(phone).matches()) return "Enter a 10-digit contact number starting with 0.";
        if (selected.isEmpty()) return "Select at least one seat.";
        if (selected.size() > MAX_SEATS) return "A customer can book up to " + MAX_SEATS + " seats.";
        if (date().compareTo(fmt.format(new Date())) < 0) return "The travel date is in the past.";
        int already = store.seatCountForId(t.no, date(), id, excludeRef);
        if (already + selected.size() > MAX_SEATS)
            return "This customer already holds " + already + " seat(s) on this train and date (max " + MAX_SEATS + ").";
        Set<String> taken = store.bookedSeats(t.no, date(), excludeRef);
        for (String k : selected) if (taken.contains(k)) return "Seat " + pretty(k) + " is already booked.";
        return null;
    }

    private List<Booking> makeBookings(Train t, String ref) {
        List<Booking> out = new ArrayList<>();
        for (String k : selected) {
            String[] p = k.split("-");
            out.add(new Booking(ref, t.no, date(), Integer.parseInt(p[0]), Integer.parseInt(p[1]),
                    idF.getText().trim().toUpperCase(), nameF.getText().trim().replace(",", " "),
                    contactF.getText().trim()));
        }
        return out;
    }

    private void doBook() {
        Train t = current();
        if (t == null) return;
        if (editingRef != null) { warn("A booking is loaded for editing. Press 'Clear / new' to start a new booking."); return; }
        if (store.bookedSeats(t.no, date(), null).size() >= t.totalSeats()) {
            warn("This train is fully booked for " + date() + ". No more seats can be booked.");
            return;
        }
        String err = validate(t, null);
        if (err != null) { warn(err); return; }
        String ref = store.nextRef();
        store.add(makeBookings(t, ref));
        if (save()) {
            JOptionPane.showMessageDialog(this, "Booking " + ref + " confirmed for " + selected.size() + " seat(s).");
            refreshAll();
        }
    }

    private void doUpdate() {
        Train t = current();
        if (t == null) return;
        if (editingRef == null) { warn("Select a booking in the table first."); return; }
        String err = validate(t, editingRef);
        if (err != null) { warn(err); return; }
        String ref = editingRef;
        store.removeRef(ref);
        store.add(makeBookings(t, ref));
        if (save()) {
            JOptionPane.showMessageDialog(this, "Booking " + ref + " updated.");
            refreshAll();
        }
    }

    private void doCancel() {
        if (editingRef == null) { warn("Select a booking in the table first."); return; }
        if (JOptionPane.showConfirmDialog(this, "Cancel booking " + editingRef + "?", "Confirm",
                JOptionPane.YES_NO_OPTION) != JOptionPane.YES_OPTION) return;
        store.removeRef(editingRef);
        if (save()) refreshAll();
    }

    private boolean save() {
        try {
            store.saveBookings();
            return true;
        } catch (IOException e) {
            warn("Could not save bookings: " + e.getMessage());
            return false;
        }
    }

    private void warn(String msg) {
        JOptionPane.showMessageDialog(this, msg, "Notice", JOptionPane.WARNING_MESSAGE);
    }

    public static void main(String[] args) {
        try { UIManager.setLookAndFeel(UIManager.getCrossPlatformLookAndFeelClassName()); }
        catch (Exception ignored) { }
        SwingUtilities.invokeLater(() -> new TrainBookingApp().setVisible(true));
    }
}
